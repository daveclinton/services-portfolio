# https://docs.djangoproject.com/en/5.2/ref/settings/#databases
#
# Either set DATABASE_URL (e.g. a Neon connection string:
# ``postgresql://user:pass@host/db?sslmode=require``) or the individual
# POSTGRES_* variables below. DATABASE_URL wins when both are set.

def _database_from_url(url: str) -> dict:
    """Parse a ``postgres://`` URL with the standard library (no new deps)."""
    from urllib.parse import parse_qs, unquote, urlparse

    parsed = urlparse(url)
    if parsed.scheme not in ("postgres", "postgresql"):
        raise ValueError(f"unsupported DATABASE_URL scheme: {parsed.scheme!r}")
    query = parse_qs(parsed.query)
    options = {
        key: values[0]
        for key in ("sslmode", "channel_binding")
        for values in [query.get(key, [])]
        if values
    }
    if os.environ.get("POSTGRES_SSLMODE"):
        options["sslmode"] = os.environ["POSTGRES_SSLMODE"]
    config = {
        'ENGINE': 'django.db.backends.postgresql',
        'NAME': unquote(parsed.path.lstrip("/")),
        'USER': unquote(parsed.username or ""),
        'PASSWORD': unquote(parsed.password or ""),
        'HOST': parsed.hostname or "",
        'PORT': str(parsed.port) if parsed.port else "",
    }
    if options:
        config['OPTIONS'] = options
    return config


def _database_config() -> dict:
    url = os.environ.get("DATABASE_URL", "").strip()
    if url:
        return _database_from_url(url)
    sslmode = os.environ.get("POSTGRES_SSLMODE")
    return {
        'ENGINE': 'django.db.backends.postgresql',
        'NAME': os.environ.get('POSTGRES_DB', 'postgres'),
        'USER': os.environ.get('POSTGRES_USER', 'postgres'),
        'PASSWORD': os.environ.get('POSTGRES_PASSWORD', 'postgres'),
        'HOST': os.environ.get('POSTGRES_HOST', 'localhost'),
        'PORT': os.environ.get('POSTGRES_PORT', '5432'),
        # Set POSTGRES_SSLMODE=require for hosted databases (Neon).
        # Left unset for local docker Postgres, which has no SSL.
        **({'OPTIONS': {'sslmode': sslmode}} if sslmode else {}),
    }


